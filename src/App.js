import React, { useState } from 'react';
// Импортируем React и хук useState — он нужен для работы с состоянием (переменными, которые могут меняться и вызывать перерисовку компонента)

import Button from './components/Button';
// Импортируем компонент Button из папки components — это отдельная часть интерфейса, которую мы переиспользуем

import './App.css';
// Подключаем стили для компонента App — классы и CSS-правила из этого файла будут применяться в этом компоненте

function App() {
    // Объявляем функциональный компонент App — он возвращает JSX (разметку), которую React отображает на странице

    const [clickCount, setClickCount] = useState(0);
    // Инициализируем состояние:
    // - clickCount — текущее количество кликов (начинается с 0)
    // - setClickCount — функция для обновления этого значения
    // При изменении clickCount React автоматически перерисует компонент

    const handleButtonClick = () => {
        // Функция-обработчик события клика по кнопке
        setClickCount(clickCount + 1);
        // Увеличиваем счётчик на 1 и передаём новое значение через setClickCount
        // Важно: состояние в React обновляется асинхронно, но для простого инкремента такой подход корректен
    };

    return (
        <div
            className="app-container"
            // Применяем CSS-класс app-container — в App.css можно описать общие стили для контейнера
            style={{
                // Динамически меняем фон в зависимости от чётности счётчика:
                // если clickCount чётный — светло‑серый (#f4f4f4), иначе — бежевый (#ffebcd)
                backgroundColor: clickCount % 2 === 0 ? '#f4f4f4' : '#ffebcd',
            }}
        >
            <Button onClick={handleButtonClick} />
            {/* Передаём функцию handleButtonClick в компонент Button через проп onClick
            Когда пользователь нажмёт на кнопку внутри Button, сработает эта функция и обновится состояние */}
        </div>
    );
}

export default App;
// Экспортируем компонент App как значение по умолчанию — так его можно импортировать в других файлах просто как App
