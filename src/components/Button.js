import React, { useState } from 'react';
// Импортируем React и хук useState: он нужен, чтобы хранить внутреннее состояние кнопки (был ли клик)

import './Button.css';
// Подключаем стили для компонента Button — классы и правила из Button.css будут применяться здесь

const Button = ({ onClick }) => {
    // Объявляем функциональный компонент Button, который принимает проп onClick
    // onClick — это функция-обработчик, переданная из родительского компонента (App)

    const [isClicked, setIsClicked] = useState(false);
    // Создаём локальное состояние кнопки:
    // - isClicked — флаг, был ли уже клик по кнопке (по умолчанию false)
    // - setIsClicked — функция для изменения этого флага
    // Это состояние «принадлежит» только кнопке и не видно снаружи

    const handleClick = () => {
        // Функция-обработчик клика по кнопке
        setIsClicked(!isClicked);
        // Переключаем флаг: если был false, станет true, и наоборот
        // Это нужно, чтобы менять стиль кнопки при клике

        onClick();
        // Вызываем внешнюю функцию, переданную из родителя (из App)
        // Так кнопка сообщает родителю: «пользователь кликнул», и родитель обновляет счётчик
    };

    return (
        <button
            // Формируем список классов: всегда есть custom-button, плюс clicked, если isClicked === true
            className={`custom-button ${isClicked ? 'clicked' : ''}`}
            // Вешаем на кнопку наш внутренний обработчик handleClick
            onClick={handleClick}>
            Изменить цвет
        </button>
    );
};

export default Button;
// Экспортируем компонент Button как значение по умолчанию, чтобы его можно было импортировать в других файлах
