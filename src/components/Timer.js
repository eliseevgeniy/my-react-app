import React, { useState, useEffect } from "react";
// Импортируем React и два хука:
// useState — для хранения состояния (значения таймера, интервал, флаг запуска).
// useEffect — для выполнения побочных эффектов (запуск/остановка таймера).

import "./Timer.css";
// Импортируем стили для компонента Timer (класс .timer и др.).

const Timer = () => {
  // Функциональный компонент Timer — отображает таймер с управлением.

  const [time, setTime] = useState(0);
  // time — сколько "тиков" прошло (в текущей версии каждый тик = 1 секунда).
  // setTime — функция для изменения значения.
  // Начальное значение — 0.

  const [intervalTime, setIntervalTime] = useState(1000); // Интервал обновления
  // intervalTime — интервал обновления таймера в миллисекундах.
  // По умолчанию 1000 мс = 1 секунда.

  const [isRunning, setIsRunning] = useState(true);
  // isRunning — флаг: работает ли таймер сейчас.
  // true — таймер идёт, false — на паузе.

  useEffect(() => {
    // useEffect выполняется после рендера компонента.
    // Здесь мы запускаем setInterval, который увеличивает time каждые intervalTime мс.
    // Второй аргумент (массив зависимостей) определяет, когда эффект перезапускается.

    if (!isRunning) return;
    // Если таймер на паузе — ничего не делаем и выходим из эффекта.
    // Это предотвращает создание интервала, когда он не нужен.

    const timer = setInterval(() => {
      // setInterval создаёт повторяющийся таймер.
      // Функция внутри будет вызываться каждые intervalTime мс.

      setTime((prev) => prev + 1);
      // Увеличиваем time на 1.
      // Используем функцию-обновление (prev => prev + 1), чтобы всегда работало
      // с актуальным значением state (важно при частых обновлениях).

    }, intervalTime);
    // Интервал берётся из состояния intervalTime (в мс).

    return () => clearInterval(timer);
    // Функция очистки (cleanup) — вызывается перед следующим запуском эффекта
    // и при размонтировании компонента.
    // Она останавливает предыдущий интервал, чтобы не было утечек и дублирования.

  }, [isRunning, intervalTime]);
  // Массив зависимостей:
  // эффект перезапустится, когда изменится isRunning (пауза/запуск)
  // или intervalTime (пользователь ввёл новый интервал).

  return (
    // Возвращаем JSX-разметку компонента.

    <div className="timer">
      {/* Корневой div с классом "timer" — стилизуется через Timer.css */}

      <h2>Таймер</h2>
      {/* Заголовок второго уровня — название блока */}

      <p>Прошло времени: {time} секунд</p>
      {/* Показываем текущее значение таймера.
          {} — вставка JS-выражения (переменной time) в JSX. */}

      <button onClick={() => setIsRunning(!isRunning)}>
        {/* Кнопка переключения паузы/запуска.
            onClick — обработчик клика. Мы передаём стрелочную функцию,
            которая инвертирует isRunning (true → false, false → true). */}

        {isRunning ? "Пауза" : "Запустить"}
        {/* Тернарный оператор:
            если таймер идёт (isRunning === true) — текст "Пауза",
            иначе — "Запустить". */}

      </button>

      <button onClick={() => setTime(0)}>Сброс</button>
      {/* Кнопка сброса. При клике устанавливаем time = 0.
          React перерисует компонент, и на экране снова будет "0 секунд". */}

      <input
        type="number"
        placeholder="Интервал (мс)"
        onChange={(e) => setIntervalTime(Number(e.target.value))}
      />
      {/* Поле ввода для нового интервала.
          type="number" — только числа.
          placeholder — подсказка внутри поля.
          onChange — вызывается при каждом изменении текста в поле.
          e.target.value — строка, поэтому преобразуем её в число через Number().
          setIntervalTime(...) обновляет состояние intervalTime,
          что приводит к перезапуску эффекта. */}

    </div>
  );
};

export default Timer;
