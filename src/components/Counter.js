import React, { useState, useEffect } from "react";
// Импортируем React и хук useState.
// useState — это встроенный хук React, который позволяет функциональному компоненту
// хранить и изменять своё состояние (state).
// Теперь импортируем ещё и useEffect — он нужен для подписки на события клавиатуры.

import "./Counter.css";
// Импортируем файл стилей Counter.css.
// Благодаря этому стили из него (например, класс .counter) применятся к этому компоненту.

const Counter = () => {
  const [count, setCount] = useState(0);
  // count — текущее значение счётчика, setCount — функция для его изменения.

  useEffect(() => {
    // useEffect выполняется после первого рендера компонента.
    // Здесь мы подписываемся на глобальное событие клавиатуры window.

    const handleKeyPress = (event) => {
      // Функция-обработчик нажатия клавиш.
      // event — объект события, в нём есть event.key — название нажатой клавиши.

      if (event.key === "ArrowUp") setCount((prev) => prev + 1);
      // Если нажата стрелка вверх — увеличиваем счётчик на 1.
      // Используем функцию-обновление (prev => prev + 1), чтобы всегда
      // работать с актуальным значением count, а не «застывшим» в замыкании.

      if (event.key === "ArrowDown") setCount((prev) => prev - 1);
      // Если нажата стрелка вниз — уменьшаем счётчик на 1.

    };

    window.addEventListener("keydown", handleKeyPress);
    // Подписываемся на событие "keydown" на объекте window.
    // Теперь нажатия клавиш работают в любом месте страницы, независимо от фокуса.

    return () => {
      window.removeEventListener("keydown", handleKeyPress);
      // Cleanup-функция: отписываемся от события при размонтировании компонента.
      // Это предотвращает утечку памяти и «висящие» обработчики.
    };

  }, []);
  // Пустой массив зависимостей [] означает:
  // эффект выполнится один раз — после первого рендера,
  // и cleanup вызовется только при размонтировании.
  // Подписка/отписка произойдут всего один раз — это эффективно.

  return (
    <div className="counter">
      <h2>Счетчик</h2>
      <p>Текущее значение: {count}</p>
      {/* Показываем текущее значение счётчика */}

      <button onClick={() => setCount(count + 1)}>Увеличить</button>
      <button onClick={() => setCount(count - 1)}>Уменьшить</button>

      <p style={{ fontSize: "14px", color: "gray" }}>
        Используйте стрелки ↑ и ↓ на клавиатуре
      </p>
      {/* Подсказка пользователю о горячих клавишах */}
    </div>
  );
};

export default Counter;
// Экспортируем компонент Counter по умолчанию,
// чтобы его можно было импортировать в других файлах как:
